class Ventas{
    cantidadItems = 0;
    precioItem = 0;
    
    obtenerCantidadItems(cantItems){
        this.cantidadItems = cantItems;
        return this.cantidadItems;
    }

    obtenerPrecioItem(precioItem){
        this.precioItem = precioItem
        return this.precioItem
    }


}
export default Ventas